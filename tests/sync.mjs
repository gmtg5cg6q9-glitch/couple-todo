import {configureFeatures,useCollection} from '../assets/features.js';
const values=new Map();
globalThis.localStorage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
globalThis.window=new EventTarget();
globalThis.CustomEvent=class extends Event {constructor(name,options){super(name);this.detail=options.detail;}};
const assert=(ok,message)=>{if(!ok)throw Error(message);};
const tick=()=>new Promise(resolve=>setTimeout(resolve,10));
let effects=[],state=[];
const react={createElement(){},useState(initial){const i=state.length;state.push(typeof initial==='function'?initial():initial);return[state[i],value=>{state[i]=value;}];},useRef(value){return {current:value};},useCallback(fn){return fn;},useEffect(fn){effects.push(fn);}};
let remote=[],offline=false,subscribed;
const api={enabled:()=>true,config:()=>({url:'https://test.invalid',coupleId:'test'}),pull:async()=>{if(offline)throw Error('offline');return remote;},upsert:async(kind,value)=>{if(offline)throw Error('offline');remote=[...remote.filter(item=>item.id!==value.id),value];},remove:async(kind,id)=>{if(offline)throw Error('offline');remote=remote.filter(item=>item.id!==id);},subscribe:(kind,callback)=>{subscribed=callback;return()=>{};}};
configureFeatures(react,api);
const collection=useCollection('todos','couple-todo-v2',[{id:'sample'}]);
assert(collection.items.length===0,'cloud must not seed sample records');
const dispose=effects.map(fn=>fn());
await tick();
assert(state[0].length===0,'initial empty cloud');
offline=true;
collection.mutate('a',{id:'a',text:'offline task',done:false});
await tick();
assert(state[0].length===1,'local edit survives network failure');
const queueKey=[...values.keys()].find(key=>key.endsWith(':pending'));
assert(JSON.parse(values.get(queueKey)).length===1,'offline queue is persisted');
offline=false;await collection.retry();
assert(remote[0].text==='offline task','retry uploads queued data');
assert(JSON.parse(values.get(queueKey)).length===0,'acknowledged queue drained');
collection.mutate('a',null);await tick();
assert(remote.length===0&&state[0].length===0,'delete final remote record');
remote=[{id:'b',text:'from partner'}];await subscribed();
assert(state[0][0].id==='b','partner update received');
remote=[];await subscribed();
assert(state[0].length===0,'partner deleting last record empties local view');
for(const cleanup of dispose)cleanup?.();
console.log({passed:9,suite:'sync lifecycle'});
